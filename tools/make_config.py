"""Generate config/recipes.json containing the main recipe EXAMPLE-BLK-3xGRY.

    python tools/make_config.py                       # teach from the default good frames
    python tools/make_config.py good1.png good2.png   # teach from your own good frames
    python tools/make_config.py --out other/recipes.json

The recipe is rebuilt from scratch: the fixed regions below, the default
thresholds from marker_engine/config.py, and colours, cable width, stripe
pitch/width, lighting reference and fixture template taught from the good
frames.  The regions are in pixels of the FIRST teach frame's resolution
(``IMAGE_SIZE``); fixture alignment adapts them to other framings.

If you change the camera mount, redraw the regions in the app (or edit them
here for the new first frame) and teach again.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from marker_engine.calibration import TeachSession  # noqa: E402
from marker_engine.config import RECIPES_FILE  # noqa: E402
from marker_engine.recipes import Recipe, RecipeStore  # noqa: E402

NAME = "EXAMPLE-BLK-3xGRY"
IMAGE_SIZE = (1806, 972)               # resolution the regions below refer to
ROI = (250, 110, 700, 100)             # x, y, w, h: around the cable
STRIPE_REGION = (420, 120, 260, 80)    # stripes plus the 'HCA' print next to them
TEACH_REGION = (420, 125, 160, 70)     # stripes only, used while teaching
DEFAULT_FRAMES = [ROOT / "samples/real/reference.png", ROOT / "samples/real/set2/06_grey.png"]


def read(path: Path) -> np.ndarray | None:
    return cv2.imdecode(np.fromfile(str(path), dtype=np.uint8), cv2.IMREAD_COLOR)


def _teach(recipe: Recipe, images: list[tuple[str, np.ndarray]], label: str) -> Recipe:
    session = TeachSession()
    used = 0
    for name, img in images:
        ok, msg = session.add_auto(img, recipe)
        used += ok
        print(f"  [{label}] {name}: {msg}")
    if not used:
        raise SystemExit(f"no usable good frame in the {label} pass - nothing taught")
    for w in session.build(recipe):
        print(f"  [{label}] warning:", w)
    return recipe


def build(frames: list[Path]) -> Recipe:
    images = []
    for p in frames:
        img = read(p)
        if img is None:
            print(f"  {p}: cannot read - skipped")
        else:
            images.append((p.name, img))
    recipe = Recipe(NAME, body_colour="black", stripe_colour="grey", stripe_count=3,
                    roi=ROI, inspection_region=STRIPE_REGION, image_size=IMAGE_SIZE,
                    notes="Main recipe: black cable with 3 grey stripes. Generated by tools/make_config.py.")
    # pass 1: stripes-only region -> stripe pitch and width (needed to set the print aside)
    geometry_view = recipe.copy()
    geometry_view.inspection_region = TEACH_REGION
    _teach(geometry_view, images, "geometry")
    recipe.geometry.update({k: geometry_view.geometry[k] for k in ("expected_spacing_px", "expected_width_px")})
    # pass 2: the real inspection region -> colours, width, lighting and fixture template,
    # measured exactly as they will be measured during inspection
    return _teach(recipe, images, "colours")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("frames", nargs="*", type=Path, help="good frames (default: reference + 06_grey)")
    ap.add_argument("--out", type=Path, default=RECIPES_FILE, help="recipes.json to write (replaced)")
    args = ap.parse_args(argv)
    frames = args.frames or [p for p in DEFAULT_FRAMES if p.exists()]
    if not frames:
        ap.error("no good frames given and the default sample frames are missing")

    print(f"teaching {NAME} from {len(frames)} frame(s)")
    recipe = build(frames)
    if args.out.exists():
        args.out.unlink()                       # rebuild from scratch: this recipe only
    saved = RecipeStore(args.out).save(recipe)
    print(f"wrote {args.out} : {saved.name} v{saved.version}")
    print(f"  body   {saved.body_ref['lab']}  tol_l {saved.body_ref['tol_l']}")
    print(f"  stripe {saved.stripe_ref['lab']}  tol_l {saved.stripe_ref['tol_l']}")
    print(f"  cable width {saved.cable_width_px:.1f}px, pitch {saved.geometry['expected_spacing_px']}px, "
          f"stripe width {saved.geometry['expected_width_px']}px, lighting L* {saved.lighting_ref_l}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
